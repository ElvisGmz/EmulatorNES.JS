const GLYPH_WIDTH = 5;
const GLYPH_HEIGHT = 7;

export function isGlyphPixel(glyph, x, y) {
  return x >= 0 && y >= 0 && x < GLYPH_WIDTH && y < GLYPH_HEIGHT && glyph[y][x] === "#";
}

/** Renders a glyph into an 8x8 tile: `ink` pixels with a `shadow` pixel down-right, like arcade text. */
export function glyphToTile(glyph, { ink = "a", shadow = "c" } = {}) {
  const rows = [];
  for (let y = 0; y < 8; y++) {
    let row = "";
    for (let x = 0; x < 8; x++) {
      const glyphX = x - 1;
      if (isGlyphPixel(glyph, glyphX, y)) row += ink;
      else if (isGlyphPixel(glyph, glyphX - 1, y - 1)) row += shadow;
      else row += ".";
    }
    rows.push(row);
  }
  return rows;
}
